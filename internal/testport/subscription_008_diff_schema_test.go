// TestPort_Subscription008DiffSchema ports postgres/src/test/subscription/t/008_diff_schema.pl
// to the M0149 contract: a subscriber table with extra columns (DEFAULT
// now(), DEFAULT 999, an identity column) gets the local defaults on copy and
// on apply, keeps locally changed extra columns across replicated UPDATEs,
// accepts a subscriber-only primary key added after the sync, and a refresh
// onto a subscriber table missing replicated columns makes the apply worker
// log "logical replication target relation … is missing replicated
// columns". It runs in three pairings: all-goopg, a PG 18.3 publisher with a
// goopg subscriber, and a goopg publisher with a PG 18.3 subscriber.
//
// Passes 3/3 in all three pairings (M0149-0040f, M0149-0044a, M0149-0044b,
// M0149-0042b).
func TestPort_Subscription008DiffSchema(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping subscription TAP port in short mode")
	}
	repo := repoRoot(t)
	tapnode.Available(t, repo)
	goopg := func(t *testing.T, name string) *tapnode.Node { return tapnode.NewGoopg(t, repo, name) }
	pg := func(t *testing.T, name string) *tapnode.Node { return tapnode.NewPG(t, repo, name) }
	cases := []struct {
		name                  string
		publisher, subscriber func(t *testing.T, name string) *tapnode.Node
	}{
		{"all-goopg", goopg, goopg},
		{"pg18-publisher-goopg-subscriber", pg, goopg},
		{"goopg-publisher-pg18-subscriber", goopg, pg},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			runSubscriptionDiffSchema(t, tc.publisher(t, "publisher"), tc.subscriber(t, "subscriber"))
		})
	}
}

// waitForSubscriberSync is Cluster.pm's wait_for_subscription_sync without a
// publisher: every pg_subscription_rel row is ready or synchronized.
func waitForSubscriberSync(t *testing.T, subscriber *tapnode.Node) {
	t.Helper()
	const q = "SELECT count(1) = 0 FROM pg_subscription_rel WHERE srsubstate NOT IN ('r', 's');"
	if !subscriber.PollQueryUntil("postgres", q, "t") {
		st, _, _ := subscriber.PSQLExit("postgres", "SELECT srrelid::regclass, srsubstate FROM pg_subscription_rel")
		t.Fatalf("timed out waiting for subscriber to synchronize data; pg_subscription_rel: %q", st)
	}
}

// waitForLog is Cluster.pm's wait_for_log(regexp, offset): the node's log
// past offset matches re within the default timeout.
func waitForLog(t *testing.T, n *tapnode.Node, re *regexp.Regexp, offset int64) {
	t.Helper()
	deadline := time.Now().Add(tapnode.TimeoutDefault())
	for time.Now().Before(deadline) {
		if re.MatchString(n.LogFrom(offset)) {
			return
		}
		time.Sleep(100 * time.Millisecond)
	}
	t.Fatalf("timed out waiting for log %q on %s; log since offset:\n%s", re, n.Name(), n.LogFrom(offset))
}

func runSubscriptionDiffSchema(t *testing.T, nodePublisher, nodeSubscriber *tapnode.Node) {
	is := func(got, want, name string) {
		t.Helper()
		if got != want {
			t.Errorf("not ok: %s: got %q, want %q", name, got, want)
		}
	}
	for _, l := range []string{"wal_level = logical", "max_wal_senders = 10", "max_replication_slots = 10"} {
		nodePublisher.AppendConf(l)
	}
	nodePublisher.Start()
	nodeSubscriber.Start()
	t.Cleanup(func() {
		if !t.Failed() {
			return
		}
		for _, n := range []*tapnode.Node{nodeSubscriber, nodePublisher} {
			for _, l := range strings.Split(fileTail(n.LogPath(), 2000), "\n") {
				if strings.Contains(l, "ERROR") || strings.Contains(l, "FATAL") || strings.Contains(l, "level=ERROR") || strings.Contains(l, "level=WARN") {
					t.Log(n.Name() + " log| " + l)
				}
			}
		}
	})

	// Create some preexisting content on publisher
	nodePublisher.SafePSQL("postgres", "CREATE TABLE test_tab (a int primary key, b varchar)")
	nodePublisher.SafePSQL("postgres", "INSERT INTO test_tab VALUES (1, 'foo'), (2, 'bar')")

	// Setup structure on subscriber
	nodeSubscriber.SafePSQL("postgres", "CREATE TABLE test_tab (a int primary key, b text, c timestamptz DEFAULT now(), d bigint DEFAULT 999, e int GENERATED BY DEFAULT AS IDENTITY)")

	// Setup logical replication
	publisherConnstr := nodePublisher.ConnStr()
	nodePublisher.SafePSQL("postgres", "CREATE PUBLICATION tap_pub FOR ALL TABLES")
	nodeSubscriber.SafePSQL("postgres", "CREATE SUBSCRIPTION tap_sub CONNECTION '"+publisherConnstr+"' PUBLICATION tap_pub")

	waitForSubscriptionSync(t, nodeSubscriber, nodePublisher, "tap_sub")

	is(nodeSubscriber.SafePSQL("postgres", "SELECT count(*), count(c), count(d = 999) FROM test_tab"), "2|2|2",
		"check initial data was copied to subscriber")

	// Update the rows on the publisher and check the additional columns on
	// subscriber didn't change
	nodePublisher.SafePSQL("postgres", "UPDATE test_tab SET b = encode(sha256(b::bytea), 'hex')")
	waitForSubCatchup(t, nodePublisher, "tap_sub")
	is(nodeSubscriber.SafePSQL("postgres", "SELECT count(*), count(c), count(d = 999), count(e) FROM test_tab"), "2|2|2|2",
		"check extra columns contain local defaults after copy")

	// Change the local values of the extra columns on the subscriber,
	// update publisher, and check that subscriber retains the expected
	// values
	nodeSubscriber.SafePSQL("postgres", "UPDATE test_tab SET c = 'epoch'::timestamptz + 987654321 * interval '1s'")
	nodePublisher.SafePSQL("postgres", "UPDATE test_tab SET b = encode(sha256(a::text::bytea), 'hex')")
	waitForSubCatchup(t, nodePublisher, "tap_sub")
	is(nodeSubscriber.SafePSQL("postgres", "SELECT count(*), count(extract(epoch from c) = 987654321), count(d = 999) FROM test_tab"), "2|2|2",
		"check extra columns contain locally changed data")

	// Check that we don't update the extra columns on insert
	nodePublisher.SafePSQL("postgres", "INSERT INTO test_tab VALUES (3, 'baz')")
	waitForSubCatchup(t, nodePublisher, "tap_sub")
	is(nodeSubscriber.SafePSQL("postgres", "SELECT count(*), count(c), count(d = 999), count(e) FROM test_tab"), "3|3|3|3",
		"check extra columns contain local defaults after apply")

	// Check a subscriber-only primary key added after the sync
	nodePublisher.SafePSQL("postgres", "CREATE TABLE test_tab2 (a int)")
	nodeSubscriber.SafePSQL("postgres", "CREATE TABLE test_tab2 (a int)")
	nodeSubscriber.SafePSQL("postgres", "ALTER SUBSCRIPTION tap_sub REFRESH PUBLICATION")
	waitForSubscriberSync(t, nodeSubscriber)
	nodeSubscriber.SafePSQL("postgres", "ALTER TABLE test_tab2 ADD COLUMN b serial PRIMARY KEY")
	nodePublisher.SafePSQL("postgres", "INSERT INTO test_tab2 VALUES (1)")
	waitForSubCatchup(t, nodePublisher, "tap_sub")
	is(nodeSubscriber.SafePSQL("postgres", "SELECT count(*), min(a), max(a) FROM test_tab2"), "1|1|1",
		"check replicated inserts on subscriber")

	// Test if the expected error is reported when the subscriber table is
	// missing columns which were specified on the publisher table.
	nodePublisher.SafePSQL("postgres", "CREATE TABLE test_tab3 (a int, b int, c int)")
	nodeSubscriber.SafePSQL("postgres", "CREATE TABLE test_tab3 (a int)")
	offset := nodeSubscriber.LogSize()
	nodeSubscriber.SafePSQL("postgres", "ALTER SUBSCRIPTION tap_sub REFRESH PUBLICATION")
	waitForLog(t, nodeSubscriber, regexp.MustCompile(`ERROR: ( [A-Z0-9]+:)? logical replication target relation "public.test_tab3" is missing replicated columns: "b", "c"`), offset)

	nodeSubscriber.Stop(tapnode.StopFast)
	nodePublisher.Stop(tapnode.StopFast)
}
