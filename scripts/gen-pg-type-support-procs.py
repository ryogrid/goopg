#!/usr/bin/env python3
"""Generate internal/initdb/pg_type_support_generated.go (M0149-0001h1a15):
pg_type.typmodin / typmodout / typanalyze / typcollation / typarray for every
pg_type row a PostgreSQL 18.3 initdb holds (OID < 16384), plus each row's
typdefault. pgTypeRow reads them so the bootstrapped rows carry the support
procedures genbki assigns (array_typanalyze for every true array type,
range_typanalyze, the typmod I/O pairs an array inherits from its element)
instead of 0. Captured from a throwaway initdb.

Usage: scripts/gen-pg-type-support-procs.py | gofmt > internal/initdb/pg_type_support_generated.go
"""
import json
import os
import shutil
import subprocess
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    q = """select coalesce(json_agg(json_build_object(
          'oid', t.oid::int8, 'name', t.typname::text,
          'modin', t.typmodin::oid::int8, 'modout', t.typmodout::oid::int8,
          'analyze', t.typanalyze::oid::int8, 'coll', t.typcollation::int8,
          'array', t.typarray::int8, 'default', t.typdefault) order by t.oid), '[]')
        from pg_type t where t.oid < 16384"""
    out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki",
                          "-d", "postgres", "-At", "-c", q], env=env, check=True, capture_output=True, text=True).stdout
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
rows = json.loads(out)
lines = [
    "// Code generated by scripts/gen-pg-type-support-procs.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n",
    "package initdb\n\n",
    "// pgTypeSupport is one pg_type row's support-procedure / collation /\n",
    "// array / default columns as a PG 18.3 initdb holds them.\n",
    "type pgTypeSupport struct {\n",
    "\tModIn, ModOut, Analyze uint32\n",
    "\tCollation, Array       uint32\n",
    "\tDefault                string // typdefault; \"\" when NULL\n",
    "\tHasDefault             bool\n",
    "}\n\n",
    "// pgTypeInitdbSupport is keyed by pg_type OID (%d rows).\n" % len(rows),
    "var pgTypeInitdbSupport = map[uint32]pgTypeSupport{\n",
]
for r in rows:
    d = r["default"]
    extra = ""
    if d is not None:
        extra = ", Default: %s, HasDefault: true" % json.dumps(d)
    lines.append("\t%d: {ModIn: %d, ModOut: %d, Analyze: %d, Collation: %d, Array: %d%s}, // %s\n" % (
        r["oid"], r["modin"], r["modout"], r["analyze"], r["coll"], r["array"], extra, r["name"]))
lines.append("}\n")
print("".join(lines), end="")
