#!/usr/bin/env python3
"""Generate internal/initdb/pg_attribute_meta_generated.go (M0149-0001g slice
17): the per-column metadata a PostgreSQL 18.3 initdb leaves in pg_attribute
for every system relation (pg_catalog / information_schema / pg_toast, OID <
16384), keyed "relname.attname": atttypid (to check goopg agrees),
attcollation, attalign, attbyval, attndims, attstorage, attnotnull, atttypmod
and attacl (bootstrap superuser rendered "B"). Captured from a throwaway initdb.

Usage: scripts/gen-pg-attribute-meta.py > internal/initdb/pg_attribute_meta_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    q = """select coalesce(json_agg(json_build_object(
          'k', c.relname || '.' || a.attname, 'typ', a.atttypid::int8, 'coll', a.attcollation::int8,
          'align', a.attalign::text, 'byval', a.attbyval, 'ndims', a.attndims, 'storage', a.attstorage::text,
          'notnull', a.attnotnull, 'typmod', a.atttypmod, 'acl', replace(a.attacl::text, 'genbki', 'B'))
          order by c.relname, a.attnum), '[]')
        from pg_attribute a join pg_class c on c.oid = a.attrelid join pg_namespace n on n.oid = c.relnamespace
        where c.oid < 16384 and n.nspname in ('pg_catalog', 'information_schema', 'pg_toast')"""
    out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki",
                          "-d", "postgres", "-At", "-c", q], env=env, check=True, capture_output=True, text=True).stdout
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
rows = json.loads(out)
lines = [
    "// Code generated by scripts/gen-pg-attribute-meta.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n",
    "package initdb\n\n",
    "// pgAttributeInitdbMeta is the pg_attribute metadata a PG 18.3 initdb leaves\n",
    "// on each system-relation column (\"relname.attname\", %d rows).\n" % len(rows),
    "var pgAttributeInitdbMeta = map[string]pgAttributeMeta{\n",
]
for r in rows:
    lines.append("\t%s: {%d, %d, '%s', %s, %d, '%s', %s, %d, %s},\n" % (
        json.dumps(r["k"]), r["typ"], r["coll"], r["align"], "true" if r["byval"] else "false", r["ndims"],
        r["storage"], "true" if r["notnull"] else "false", r["typmod"], json.dumps(r["acl"] or "")))
lines.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(lines), capture_output=True, text=True, check=True).stdout)
