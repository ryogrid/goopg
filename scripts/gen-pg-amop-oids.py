#!/usr/bin/env python3
"""Generate internal/initdb/pg_amop_oids_generated.go from PostgreSQL 18.3's
postgres.bki (M0149-0001g slice 8).

pg_amop.dat gives no explicit OIDs; genbki assigns them from 10000 in file
order. goopg builds its pg_amop rows in a different order, so each row takes
its PG OID by natural key (amopfamily, amoplefttype, amoprighttype,
amopstrategy), which pg_amop_fam_strat_index makes unique.

Usage: scripts/gen-pg-amop-oids.py > internal/initdb/pg_amop_oids_generated.go
"""
import os
import subprocess
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bki = os.path.join(root, "postgres", "src", "include", "catalog", "postgres.bki")
rows, inside = [], False
with open(bki) as f:
    for line in f:
        line = line.rstrip("\n")
        if line.startswith("create pg_amop "):
            inside = True
        elif line == "close pg_amop":
            inside = False
        elif inside and line.startswith("insert ( "):
            fld = line[len("insert ( "):-len(" )")].split()
            rows.append(fld)
if len(rows) == 0:
    sys.exit("no pg_amop rows in " + bki)
lines = []
out = type("W", (), {"write": lambda self, x: lines.append(x)})()
out.write("// Code generated by scripts/gen-pg-amop-oids.py from postgres/src/include/catalog/postgres.bki; DO NOT EDIT.\n\n")
out.write("package initdb\n\n")
out.write("// pgAmopOIDByKey maps (amopfamily, amoplefttype, amoprighttype, amopstrategy)\n")
out.write("// to the OID PostgreSQL 18.3's genbki assigns that pg_amop row (%d rows).\n" % len(rows))
out.write("var pgAmopOIDByKey = map[pgAmopKey]uint32{\n")
for r in rows:
    out.write("\t{%s, %s, %s, %s}: %s,\n" % (r[1], r[2], r[3], r[4], r[0]))
out.write("}\n")
# gofmt aligns the map values; emit exactly what gofmt would.
sys.stdout.write(subprocess.run(["gofmt"], input="".join(lines), capture_output=True, text=True, check=True).stdout)
