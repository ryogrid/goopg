#!/usr/bin/env python3
"""Generate internal/initdb/pg_plpgsql_generated.go (M0149-0001g slice 29):
the rows a PostgreSQL 18.3 initdb's CREATE EXTENSION plpgsql leaves
(postgres/src/pl/plpgsql/src/plpgsql--1.0.sql): the three handler functions
(pg_proc), the plpgsql language (pg_language), the extension (pg_extension)
and its pg_depend rows. The two descriptions come from
scripts/gen-pg-description.py. Captured from a throwaway initdb.

Usage: scripts/gen-pg-plpgsql.py > internal/initdb/pg_plpgsql_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)

    def q(sql):
        out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki",
                              "-d", "postgres", "-At", "-c", sql], env=env, check=True, capture_output=True, text=True).stdout
        return json.loads(out)
    ext = q("select json_agg(json_build_array(oid::int8, extname::text, extnamespace::int8, extrelocatable, extversion) "
            "order by oid) from pg_extension where extname = 'plpgsql'")
    lang = q("select json_agg(json_build_array(oid::int8, lanname::text, lanispl, lanpltrusted, lanplcallfoid::int8, "
             "laninline::int8, lanvalidator::int8) order by oid) from pg_language where lanname = 'plpgsql'")
    langoid = lang[0][0]
    procs = q("select coalesce(json_agg(json_build_array(p.oid::int8, p.proname::text, p.prorettype::int8, "
              "(select coalesce(json_agg(x::int8), '[]') from unnest(p.proargtypes) x), p.provolatile::text, "
              "p.proparallel::text, p.proisstrict, p.prolang::int8, p.prosrc, coalesce(p.probin, ''), p.procost::int8, "
              "p.prorows::int8) order by p.oid), '[]') from pg_proc p where p.oid in "
              "(select lanplcallfoid from pg_language where oid = %d union select laninline from pg_language where oid = %d "
              "union select lanvalidator from pg_language where oid = %d)" % (langoid, langoid, langoid))
    deps = q("select coalesce(json_agg(json_build_array(classid::int8, objid::int8, objsubid, refclassid::int8, "
             "refobjid::int8, refobjsubid, deptype::text) order by ctid), '[]') from pg_depend "
             "where (refclassid = 'pg_extension'::regclass and refobjid = %d) or (classid = 'pg_language'::regclass "
             "and objid = %d)" % (ext[0][0], langoid))
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
J = lambda s: json.dumps(s, ensure_ascii=True)
B = lambda b: "true" if b else "false"
o = ["// Code generated by scripts/gen-pg-plpgsql.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n", "package initdb\n\n",
     "// pgPlpgsqlProcs are the handler functions CREATE EXTENSION plpgsql creates.\n",
     "var pgPlpgsqlProcs = []pgProcEntry{\n"]
for oid, name, ret, args, vol, par, strict, lang_, src, binp, cost, rows in procs:
    o.append("\t{OID: %d, Name: %s, RetType: %d, ArgTypes: []uint32{%s}, Volatile: '%s', Parallel: '%s', NotStrict: %s, Lang: %d, "
             "HandlerName: %s, Kind: 'f', Cost: %d, Rows: %d, Bin: %s},\n" % (oid, J(name), ret, ", ".join(str(a) for a in args),
             vol, par, B(not strict), lang_, J(src), cost, rows, J(binp)))
o.append("}\n\n// pgPlpgsqlLanguage is the plpgsql pg_language row.\nvar pgPlpgsqlLanguage = pgLanguageEntry{%d, %s, 10, %s, %s, %d, %d, %d}\n"
         % (lang[0][0], J(lang[0][1]), B(lang[0][2]), B(lang[0][3]), lang[0][4], lang[0][5], lang[0][6]))
e = ext[0]
o.append("\n// pgPlpgsqlExtension is the plpgsql pg_extension row (extconfig / extcondition NULL).\n"
         "var pgPlpgsqlExtension = pgExtensionEntry{OID: %d, Name: %s, Namespace: %d, Relocatable: %s, Version: %s}\n"
         % (e[0], J(e[1]), e[2], B(e[3]), J(e[4])))
o.append("\n// pgPlpgsqlDepends are the extension's pg_depend rows, in heap order.\nvar pgPlpgsqlDepends = []pgDependEntry{\n")
for d in deps:
    o.append("\t{%d, %d, %d, %d, %d, %d, '%s'},\n" % tuple(d))
o.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(o), capture_output=True, text=True, check=True).stdout)
