#!/usr/bin/env python3
"""Generate internal/catalog/pg_description_generated.go (M0149-0001g slices 19, 23):
the pg_description rows a PostgreSQL 18.3 initdb holds for objects with fixed
pg_*.dat OIDs (objoid < 10000) in catalogs goopg bootstraps, and every
pg_shdescription row. Captured from a throwaway initdb. initdb writes them to
the on-disk catalogs and goopg's comment store is seeded from them.

Usage: scripts/gen-pg-description.py > internal/catalog/pg_description_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
# pg_proc, pg_operator, pg_conversion, pg_type, pg_am, pg_collation,
# pg_namespace, pg_language: catalogs whose bki rows goopg bootstraps.
classes = "1255, 2617, 2607, 1247, 2601, 3456, 2615, 2612"
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)

    def q(sql):
        return json.loads(subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki",
                                          "-d", "postgres", "-At", "-c", sql], env=env, check=True, capture_output=True,
                                         text=True).stdout)
    local = q("select coalesce(json_agg(json_build_array(objoid::int8, classoid::int8, objsubid, description) "
              "order by objoid, classoid, objsubid), '[]') from pg_description "
              "where objoid < 10000 and classoid in (%s)" % classes)
    shared = q("select coalesce(json_agg(json_build_array(objoid::int8, classoid::int8, description) "
               "order by objoid, classoid), '[]') from pg_shdescription")
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
lines = [
    "// Code generated by scripts/gen-pg-description.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n",
    "package catalog\n\n",
    "// PGInitdbDescriptions holds pg_description rows of built-in objects (%d rows).\n" % len(local),
    "var PGInitdbDescriptions = []InitdbDescription{\n",
]
for o, c, s, d in local:
    lines.append("\t{%d, %d, %d, %s},\n" % (o, c, s, json.dumps(d, ensure_ascii=True)))
lines.append("}\n\n// PGInitdbShdescriptions holds every pg_shdescription row (%d rows).\n" % len(shared))
lines.append("var PGInitdbShdescriptions = []InitdbDescription{\n")
for o, c, d in shared:
    lines.append("\t{%d, %d, 0, %s},\n" % (o, c, json.dumps(d, ensure_ascii=True)))
lines.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(lines), capture_output=True, text=True, check=True).stdout)
