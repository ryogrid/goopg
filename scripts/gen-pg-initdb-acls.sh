#!/usr/bin/env bash
# gen-pg-initdb-acls.sh — regenerate internal/initdb/pg_initdb_acls_generated.go
# (M0149-0001g slices 12-13): the ACLs a PostgreSQL 18.3 initdb leaves on system
# objects — pg_class.relacl keyed "nspname.relname" and pg_proc.proacl keyed by
# function OID (pg_proc.dat OIDs are fixed). It runs its own throwaway initdb
# from postgres/local_install (so the tables never depend on a scratch server's
# state), renders the bootstrap superuser as "B", and stops the server.
#
# Usage: scripts/gen-pg-initdb-acls.sh > internal/initdb/pg_initdb_acls_generated.go
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
bin=$repo/postgres/local_install/bin
export LD_LIBRARY_PATH=$repo/postgres/local_install/lib
tmp=$(mktemp -d)
port=${GEN_PORT:-5547}
trap '"$bin/pg_ctl" -D "$tmp/data" -m immediate stop >/dev/null 2>&1 || true; rm -rf "$tmp"' EXIT
"$bin/initdb" -D "$tmp/data" -U genbki --no-sync -E UTF8 --locale=C >/dev/null 2>&1
"$bin/pg_ctl" -D "$tmp/data" -o "-p $port -c listen_addresses=127.0.0.1 -c unix_socket_directories=$tmp" -l "$tmp/log" -w start >/dev/null
q() { "$bin/psql" -X -h 127.0.0.1 -p "$port" -U genbki -d postgres -At -F' ' -c "$1"; }
relacl=$(q "select n.nspname || '.' || c.relname, replace(c.relacl::text, 'genbki', 'B')
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where c.oid < 16384 and c.relacl is not null order by 1")
proacl=$(q "select oid, replace(proacl::text, 'genbki', 'B')
  from pg_proc where oid < 16384 and proacl is not null order by oid")
{
	echo "// Code generated by scripts/gen-pg-initdb-acls.sh from a PostgreSQL 18.3 initdb; DO NOT EDIT."
	echo
	echo "package initdb"
	echo
	echo "// pgClassInitdbRelACL is the pg_class.relacl text a PG 18.3 initdb leaves on"
	echo "// each system relation (\"nspname.relname\"); \"B\" is the bootstrap superuser."
	echo "// Relations not listed keep relacl NULL."
	echo "var pgClassInitdbRelACL = map[string]string{"
	while read -r name acl; do printf '\t"%s": "%s",\n' "$name" "$acl"; done <<<"$relacl"
	echo "}"
	echo
	echo "// pgProcInitdbProACL is the pg_proc.proacl text a PG 18.3 initdb leaves on a"
	echo "// built-in function (system_functions.sql's REVOKE EXECUTE … FROM PUBLIC and"
	echo "// GRANTs to predefined roles), keyed by function OID. Others keep NULL."
	echo "var pgProcInitdbProACL = map[uint32]string{"
	while read -r oid acl; do printf '\t%s: "%s",\n' "$oid" "$acl"; done <<<"$proacl"
	echo "}"
} | gofmt
