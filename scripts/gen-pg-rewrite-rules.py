#!/usr/bin/env python3
"""Generate internal/initdb/pg_rewrite_rules_generated.go (M0149-0001g slice
32): the non-_RETURN rewrite rules a PostgreSQL 18.3 initdb creates
(system_views.sql's CREATE RULE pg_settings_u / pg_settings_n), with ev_qual and
ev_action exactly as PG stored them. The views' _RETURN rules come from the
nailed-view manifest. Captured from a throwaway initdb.

Usage: scripts/gen-pg-rewrite-rules.py > internal/initdb/pg_rewrite_rules_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki", "-d", "postgres",
                          "-At", "-c", "select coalesce(json_agg(json_build_array(oid::int8, rulename::text, ev_class::int8, "
                          "ev_type::text, ev_enabled::text, is_instead, ev_qual::text, ev_action::text) order by oid), '[]') "
                          "from pg_rewrite where rulename <> '_RETURN'"],
                         env=env, check=True, capture_output=True, text=True).stdout
    rules = json.loads(out)
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
J = lambda s: json.dumps(s, ensure_ascii=True)
o = ["// Code generated by scripts/gen-pg-rewrite-rules.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n", "package initdb\n\n",
     "// pgRewriteInitdbRules are the non-_RETURN rules a PG 18.3 initdb creates.\n",
     "var pgRewriteInitdbRules = []pgRewriteEntry{\n"]
for oid, name, cls, typ, en, inst, qual, act in rules:
    o.append("\t{OID: %d, RuleName: %s, EvClass: %d, EvType: '%s', EvEnabled: '%s', IsInstead: %s, EvQual: %s, EvAction: %s},\n"
             % (oid, J(name), cls, typ, en, "true" if inst else "false", J(qual), J(act)))
o.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(o), capture_output=True, text=True, check=True).stdout)
