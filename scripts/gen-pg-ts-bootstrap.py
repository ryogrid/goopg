#!/usr/bin/env python3
"""Generate internal/initdb/pg_ts_bootstrap_generated.go (M0149-0001g slice 20)
from PostgreSQL 18.3's postgres.bki: the bootstrap rows of pg_ts_parser,
pg_ts_template, pg_ts_dict, pg_ts_config and pg_ts_config_map (the default
parser, the simple/synonym/ispell/thesaurus templates, the simple dictionary and
the simple configuration with its token map).

Usage: scripts/gen-pg-ts-bootstrap.py > internal/initdb/pg_ts_bootstrap_generated.go
"""
import os
import subprocess
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bki = os.path.join(root, "postgres", "src", "include", "catalog", "postgres.bki")
want = ["pg_ts_parser", "pg_ts_template", "pg_ts_dict", "pg_ts_config", "pg_ts_config_map"]
rows = {c: [] for c in want}
cur = None
with open(bki) as f:
    for line in f:
        line = line.rstrip("\n")
        if line.startswith("create "):
            name = line.split()[1]
            cur = name if name in rows else None
        elif line.startswith("close "):
            cur = None
        elif cur and line.startswith("insert ( "):
            rows[cur].append(line[len("insert ( "):-len(" )")].split())
if not all(rows.values()):
    sys.exit("missing pg_ts_* rows in postgres.bki")
o = ["// Code generated by scripts/gen-pg-ts-bootstrap.py from postgres/src/include/catalog/postgres.bki; DO NOT EDIT.\n\n",
     "package initdb\n\n"]
o.append("var pgTSParserBKI = []pgTSParserRow{\n")
for r in rows["pg_ts_parser"]:
    o.append('\t{%s, "%s", %s, %s, %s, %s, %s, %s},\n' % tuple(r))
o.append("}\n\nvar pgTSTemplateBKI = []pgTSTemplateRow{\n")
for r in rows["pg_ts_template"]:
    o.append('\t{%s, "%s", %s, %s, %s},\n' % tuple(r))
o.append("}\n\nvar pgTSDictBKI = []pgTSDictRow{\n")
for r in rows["pg_ts_dict"]:
    if r[5] != "_null_":
        sys.exit("pg_ts_dict dictinitoption not modelled")
    o.append('\t{%s, "%s", %s, %s, %s, ""},\n' % tuple(r[:5]))
o.append("}\n\nvar pgTSConfigBKI = []pgTSConfigRow{\n")
for r in rows["pg_ts_config"]:
    o.append('\t{%s, "%s", %s, %s, %s},\n' % tuple(r))
o.append("}\n\nvar pgTSConfigMapBKI = []pgTSConfigMapRow{\n")
for r in rows["pg_ts_config_map"]:
    o.append("\t{%s, %s, %s, %s},\n" % tuple(r))
o.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(o), capture_output=True, text=True, check=True).stdout)
