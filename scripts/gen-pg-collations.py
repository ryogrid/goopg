#!/usr/bin/env python3
"""Generate internal/initdb/pg_collation_generated.go (M0149-0001g slice 33):
the pg_collation rows a PostgreSQL 18.3 initdb imports after bootstrap
(initdb.c setup_collation → pg_import_system_collations: the libc locales of
`locale -a` and every ICU locale), in heap order, plus the final values of the
seven pg_collation.dat rows (setup_collation stamps the ICU 'unicode'
collation's collversion). The import is host- and ICU-version-dependent, like
PG's own: this captures the build host's PG 18.3 initdb. Captured from a
throwaway initdb.

Usage: scripts/gen-pg-collations.py > internal/initdb/pg_collation_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki", "-d", "postgres",
                          "-At", "-c", "select coalesce(json_agg(json_build_array(oid::int8, collname::text, collnamespace::int8, "
                          "collprovider::text, collisdeterministic, collencoding, coalesce(collcollate, ''), coalesce(collctype, ''), "
                          "coalesce(colllocale, ''), coalesce(collicurules, ''), coalesce(collversion, '')) order by ctid), '[]') "
                          "from pg_collation"],
                         env=env, check=True, capture_output=True, text=True).stdout
    rows = json.loads(out)
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
J = lambda s: json.dumps(s, ensure_ascii=True)
B = lambda b: "true" if b else "false"
o = ["// Code generated by scripts/gen-pg-collations.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n", "package initdb\n\n",
     "// pgCollationInitdb is every pg_collation row of a PG 18.3 initdb in heap order\n",
     "// (%d rows): the pg_collation.dat rows as setup_collation leaves them, then the\n" % len(rows),
     "// imported libc and ICU collations.\n",
     "var pgCollationInitdb = []pgCollationEntry{\n"]
for oid, name, nsp, prov, det, enc, coll, ctype, loc, rules, ver in rows:
    o.append("\t{%d, %s, %d, 10, '%s', %s, %d, %s, %s, %s, %s, %s},\n" % (oid, J(name), nsp, prov, B(det), enc,
             J(coll), J(ctype), J(loc), J(rules), J(ver)))
o.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(o), capture_output=True, text=True, check=True).stdout)
