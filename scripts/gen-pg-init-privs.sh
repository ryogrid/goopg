#!/usr/bin/env bash
# gen-pg-init-privs.sh — regenerate internal/catalog/pg_init_privs_generated.go
# (M0149-0001g slice 22): the pg_init_privs rows a PostgreSQL 18.3 initdb
# records in setup_privileges() (postgres/src/bin/initdb/initdb.c) — the
# initial ACL of every system relation, column, function and namespace that
# carries a non-default ACL at the end of initdb. Rows are emitted in heap
# (ctid) order so goopg's bootstrap heap matches PG's tuple placement. It runs
# its own throwaway initdb from postgres/local_install, renders the bootstrap
# superuser as "B", and stops the server.
#
# Usage: scripts/gen-pg-init-privs.sh > internal/catalog/pg_init_privs_generated.go
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
bin=$repo/postgres/local_install/bin
export LD_LIBRARY_PATH=$repo/postgres/local_install/lib
tmp=$(mktemp -d)
port=${GEN_PORT:-5547}
trap '"$bin/pg_ctl" -D "$tmp/data" -m immediate stop >/dev/null 2>&1 || true; rm -rf "$tmp"' EXIT
"$bin/initdb" -D "$tmp/data" -U genbki --no-sync -E UTF8 --locale=C >/dev/null 2>&1
"$bin/pg_ctl" -D "$tmp/data" -o "-p $port -c listen_addresses=127.0.0.1 -c unix_socket_directories=$tmp" -l "$tmp/log" -w start >/dev/null
q() { "$bin/psql" -X -h 127.0.0.1 -p "$port" -U genbki -d postgres -At -F' ' -c "$1"; }
rows=$(q "select objoid, classoid::int8, objsubid, privtype, replace(initprivs::text, 'genbki', 'B')
  from pg_init_privs order by ctid")
{
	echo "// Code generated by scripts/gen-pg-init-privs.sh from a PostgreSQL 18.3 initdb; DO NOT EDIT."
	echo
	echo "package catalog"
	echo
	echo "// PGInitdbInitPrivs lists the pg_init_privs rows of a PG 18.3 initdb in heap"
	echo "// order: objoid, classoid, objsubid, privtype and the initprivs aclitem[]"
	echo "// text, in which \"B\" is the bootstrap superuser."
	echo "var PGInitdbInitPrivs = []InitdbInitPriv{"
	while read -r objoid classoid subid ptype acl; do
		printf '\t{%s, %s, %s, '"'"'%s'"'"', "%s"},\n' "$objoid" "$classoid" "$subid" "$ptype" "$acl"
	done <<<"$rows"
	echo "}"
} | gofmt
