#!/usr/bin/env python3
"""Generate internal/initdb/pg_proc_bki_attrs_generated.go from PostgreSQL
18.3's postgres.bki (M0149-0001g slice 15): the scalar attribute columns of
every pg_proc.dat row — procost, prorows, provariadic, prosupport, prokind,
prosecdef, proleakproof, proisstrict, proretset, provolatile, proparallel —
plus probin, keyed by function OID. pgProcRow overlays them on goopg's seed so
the pg_proc heap a PostgreSQL node reads carries PG's values (goopg's seed had
left 2455 functions VOLATILE that PG marks IMMUTABLE or STABLE).

Usage: scripts/gen-pg-proc-attrs.py > internal/initdb/pg_proc_bki_attrs_generated.go
"""
import os
import subprocess
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bki = os.path.join(root, "postgres", "src", "include", "catalog", "postgres.bki")


def fields(line):
    """Split a bki insert body, honouring single-quoted fields."""
    body = line[len("insert ( "):-len(" )")]
    out, cur, q, quoted = [], "", False, False
    for ch in body:
        if ch == "'":
            q, quoted = not q, True
            continue
        if ch == " " and not q:
            if cur or quoted:
                out.append(cur)
            cur, quoted = "", False
            continue
        cur += ch
    if cur or quoted:
        out.append(cur)
    return out


rows, inside = [], False
with open(bki) as f:
    for line in f:
        line = line.rstrip("\n")
        if line.startswith("create pg_proc "):
            inside = True
        elif line == "close pg_proc":
            inside = False
        elif inside and line.startswith("insert ( "):
            rows.append(fields(line))
if any(len(r) != 30 for r in rows):
    sys.exit("pg_proc row with %d fields" % min(len(r) for r in rows))
if len(rows) < 3000:
    sys.exit("parsed only %d pg_proc rows" % len(rows))


def oid(v):
    return "0" if v == "-" else v


def b(v):
    return "true" if v == "t" else "false"


lines = [
    "// Code generated by scripts/gen-pg-proc-attrs.py from postgres/src/include/catalog/postgres.bki; DO NOT EDIT.\n\n",
    "package initdb\n\n",
    "// pgProcBKIAttrsByOID holds PostgreSQL 18.3's pg_proc.dat scalar attributes\n",
    "// for every built-in function (%d rows).\n" % len(rows),
    "var pgProcBKIAttrsByOID = map[uint32]pgProcBKIAttrs{\n",
]
for r in rows:
    probin = "" if r[26] == "_null_" else r[26]
    lines.append(
        "\t%s: {%s, %s, %s, %s, '%s', %s, %s, %s, %s, '%s', '%s', %s},\n"
        % (r[0], r[5], r[6], oid(r[7]), oid(r[8]), r[9], b(r[10]), b(r[11]), b(r[12]), b(r[13]), r[14], r[15], '"%s"' % probin)
    )
lines.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(lines), capture_output=True, text=True, check=True).stdout)
