#!/usr/bin/env bash
# gen-pg-class-relacl.sh — regenerate internal/initdb/pg_class_relacl_generated.go
# (M0149-0001g slice 12): the pg_class.relacl a PostgreSQL 18.3 initdb leaves on
# every system relation, keyed "nspname.relname". It runs its own throwaway
# initdb from postgres/local_install (so the table never depends on a scratch
# server's state), reads relacl with the bootstrap superuser rendered as "B",
# and stops the server.
#
# Usage: scripts/gen-pg-class-relacl.sh > internal/initdb/pg_class_relacl_generated.go
set -euo pipefail
repo=$(cd "$(dirname "$0")/.." && pwd)
bin=$repo/postgres/local_install/bin
export LD_LIBRARY_PATH=$repo/postgres/local_install/lib
tmp=$(mktemp -d)
port=${GEN_PORT:-5547}
trap '"$bin/pg_ctl" -D "$tmp/data" -m immediate stop >/dev/null 2>&1 || true; rm -rf "$tmp"' EXIT
"$bin/initdb" -D "$tmp/data" -U genbki --no-sync -E UTF8 --locale=C >/dev/null 2>&1
"$bin/pg_ctl" -D "$tmp/data" -o "-p $port -c listen_addresses=127.0.0.1 -c unix_socket_directories=$tmp" -l "$tmp/log" -w start >/dev/null
rows=$("$bin/psql" -X -h 127.0.0.1 -p "$port" -U genbki -d postgres -At -F' ' -c "
  select n.nspname || '.' || c.relname, replace(c.relacl::text, 'genbki', 'B')
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where c.oid < 16384 and c.relacl is not null
  order by 1")
{
	echo "// Code generated by scripts/gen-pg-class-relacl.sh from a PostgreSQL 18.3 initdb; DO NOT EDIT."
	echo
	echo "package initdb"
	echo
	echo "// pgClassInitdbRelACL is the pg_class.relacl text a PG 18.3 initdb leaves on"
	echo "// each system relation (\"nspname.relname\"); \"B\" is the bootstrap superuser."
	echo "// Relations not listed keep relacl NULL."
	echo "var pgClassInitdbRelACL = map[string]string{"
	while read -r name acl; do
		printf '\t"%s": "%s",\n' "$name" "$acl"
	done <<<"$rows"
	echo "}"
} | gofmt
