#!/usr/bin/env python3
"""Generate internal/catalog/pg_depend_generated.go (M0149-0001g slices 31, 34):
every pg_depend row a PostgreSQL 18.3 initdb leaves, in heap (ctid) order —
the dependencies initdb's post-bootstrap SQL records for system views,
information_schema, the snowball text-search objects and plpgsql (bootstrap
objects are pinned by OID and carry no rows). Captured from a throwaway initdb.

Usage: scripts/gen-pg-depend.py > internal/catalog/pg_depend_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki", "-d", "postgres",
                          "-At", "-c", "select coalesce(json_agg(json_build_array(classid::int8, objid::int8, objsubid, "
                          "refclassid::int8, refobjid::int8, refobjsubid, deptype::text) order by ctid), '[]') from pg_depend"],
                         env=env, check=True, capture_output=True, text=True).stdout
    deps = json.loads(out)
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
o = ["// Code generated by scripts/gen-pg-depend.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n", "package catalog\n\n",
     "// PGDependInitdb is every pg_depend row of a PG 18.3 initdb, in heap order (%d rows).\n" % len(deps),
     "var PGDependInitdb = []InitdbDepend{\n"]
for d in deps:
    o.append("\t{%d, %d, %d, %d, %d, %d, '%s'},\n" % tuple(d))
o.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(o), capture_output=True, text=True, check=True).stdout)
