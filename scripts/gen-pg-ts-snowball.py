#!/usr/bin/env python3
"""Generate internal/initdb/pg_ts_snowball_generated.go (M0149-0001g slice 21):
what a PostgreSQL 18.3 initdb adds for snowball text search after bootstrap
(snowball_create.sql): the dict_snowball C functions (pg_proc), the snowball
template, the per-language dictionaries and configurations, their token maps,
and the descriptions of all of these. Captured from a throwaway initdb.

Usage: scripts/gen-pg-ts-snowball.py > internal/initdb/pg_ts_snowball_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)

    def q(sql):
        out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki",
                              "-d", "postgres", "-At", "-c", sql], env=env, check=True, capture_output=True, text=True).stdout
        return json.loads(out)
    tmpl = q("select coalesce(json_agg(json_build_array(oid::int8, tmplname::text, tmplnamespace::int8, tmplinit::oid::int8, "
             "tmpllexize::oid::int8) order by oid), '[]') from pg_ts_template where oid >= 10000")
    tmpl_oids = [t[0] for t in tmpl]
    procs = q("select coalesce(json_agg(json_build_array(p.oid::int8, p.proname::text, p.prorettype::int8, "
              "(select coalesce(json_agg(x::int8), '[]') from unnest(p.proargtypes) x), p.provolatile::text, "
              "p.proparallel::text, p.proisstrict, p.prolang::int8, p.prosrc, coalesce(p.probin, ''), p.procost::int8, "
              "p.prorows::int8) order by p.oid), '[]') from pg_proc p where p.oid in "
              "(select tmplinit from pg_ts_template where oid >= 10000 union select tmpllexize from pg_ts_template where oid >= 10000)")
    dicts = q("select coalesce(json_agg(json_build_array(oid::int8, dictname::text, dictnamespace::int8, dictowner::int8, "
              "dicttemplate::int8, coalesce(dictinitoption, '')) order by oid), '[]') from pg_ts_dict where oid >= 10000")
    cfgs = q("select coalesce(json_agg(json_build_array(oid::int8, cfgname::text, cfgnamespace::int8, cfgowner::int8, "
             "cfgparser::int8) order by oid), '[]') from pg_ts_config where oid >= 10000")
    maps = q("select coalesce(json_agg(json_build_array(mapcfg::int8, maptokentype, mapseqno, mapdict::int8) "
             "order by mapcfg, maptokentype, mapseqno), '[]') from pg_ts_config_map where mapcfg >= 10000")
    descs = q("select coalesce(json_agg(json_build_array(objoid::int8, classoid::int8, objsubid, description) "
              "order by objoid, classoid, objsubid), '[]') from pg_description d where objoid >= 10000 and objoid < 16384 "
              "and classoid in ('pg_ts_template'::regclass, 'pg_ts_dict'::regclass, 'pg_ts_config'::regclass, 'pg_proc'::regclass) "
              "and (classoid <> 'pg_proc'::regclass or objoid in (select tmplinit from pg_ts_template union select tmpllexize from pg_ts_template))")
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
J = lambda s: json.dumps(s, ensure_ascii=True)
o = ["// Code generated by scripts/gen-pg-ts-snowball.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n", "package initdb\n\n",
     "// pgTSSnowballProcs are the dict_snowball C functions snowball_create.sql creates.\n",
     "var pgTSSnowballProcs = []pgProcEntry{\n"]
for oid, name, ret, args, vol, par, strict, lang, src, binp, cost, rows in procs:
    o.append("\t{OID: %d, Name: %s, RetType: %d, ArgTypes: []uint32{%s}, Volatile: '%s', Parallel: '%s', NotStrict: %s, Lang: %d, "
             "HandlerName: %s, Kind: 'f', Cost: %d, Rows: %d, Bin: %s},\n" % (oid, J(name), ret, ", ".join(str(a) for a in args),
             vol, par, "false" if strict else "true", lang, J(src), cost, rows, J(binp)))
o.append("}\n\nvar pgTSTemplateInitdb = []pgTSTemplateRow{\n")
for r in tmpl:
    o.append("\t{%d, %s, %d, %d, %d},\n" % (r[0], J(r[1]), r[2], r[3], r[4]))
o.append("}\n\nvar pgTSDictInitdb = []pgTSDictRow{\n")
for r in dicts:
    o.append("\t{%d, %s, %d, %d, %d, %s},\n" % (r[0], J(r[1]), r[2], r[3], r[4], J(r[5])))
o.append("}\n\nvar pgTSConfigInitdb = []pgTSConfigRow{\n")
for r in cfgs:
    o.append("\t{%d, %s, %d, %d, %d},\n" % (r[0], J(r[1]), r[2], r[3], r[4]))
o.append("}\n\nvar pgTSConfigMapInitdb = []pgTSConfigMapRow{\n")
for r in maps:
    o.append("\t{%d, %d, %d, %d},\n" % tuple(r))
o.append("}\n\n// pgDescriptionInitdbTS holds the descriptions of the objects above.\nvar pgDescriptionInitdbTS = []pgDescriptionRow{\n")
for r in descs:
    o.append("\t{%d, %d, %d, %s},\n" % (r[0], r[1], r[2], J(r[3])))
o.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(o), capture_output=True, text=True, check=True).stdout)
