#!/usr/bin/env python3
"""Generate internal/initdb/pg_proc_view_rows_generated.go (M0149-0001h1a18):
every pg_proc row a PostgreSQL 18.3 initdb holds (OID < 16384), rendered as
the virtual pg_proc view's text cells in registerPgProcView's column order.
SQL NULL is emitted as catalog.VirtualNull; regproc / oid columns as numeric
OIDs. Captured from a throwaway initdb whose superuser is "postgres" (so
proacl grantor names match goopg's bootstrap role).

Usage: scripts/gen-pg-proc-view-rows.py | gofmt > internal/initdb/pg_proc_view_rows_generated.go
"""
import json
import os
import shutil
import subprocess
import tempfile

COLS = ["oid", "proname", "pronamespace", "prolang", "prorettype", "proargtypes", "pronargs", "proacl",
        "proowner", "prosrc", "provolatile", "prosecdef", "proleakproof", "proisstrict", "prokind",
        "proretset", "probin", "proconfig", "procost", "prorows", "protrftypes", "proparallel",
        "prosupport", "provariadic", "pronargdefaults", "proallargtypes", "proargmodes", "proargnames",
        "proargdefaults", "prosqlbody"]
EXPR = {"oid": "oid::int8::text", "prosupport": "prosupport::oid::int8::text",
        "prosecdef": "case when prosecdef then 't' else 'f' end",
        "proleakproof": "case when proleakproof then 't' else 'f' end",
        "proisstrict": "case when proisstrict then 't' else 'f' end",
        "proretset": "case when proretset then 't' else 'f' end"}

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "postgres", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    sel = ", ".join(EXPR.get(c, c + "::text") for c in COLS)
    q = "select coalesce(json_agg(json_build_array(%s) order by oid), '[]') from pg_proc where oid < 16384" % sel
    out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "postgres",
                          "-d", "postgres", "-At", "-c", q], env=env, check=True, capture_output=True, text=True).stdout
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
rows = json.loads(out)
cell = lambda v: "vn" if v is None else json.dumps(v, ensure_ascii=False)
lines = [
    "// Code generated by scripts/gen-pg-proc-view-rows.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n",
    "package initdb\n\n",
    "import \"github.com/goopg/goopg/internal/catalog\"\n\n",
    "const vn = catalog.VirtualNull\n\n",
    "// pgProcInitdbViewRows are the %d built-in pg_proc rows, one text cell per\n" % len(rows),
    "// registerPgProcView column (%s).\n" % ", ".join(COLS),
    "var pgProcInitdbViewRows = [][]string{\n",
]
for r in rows:
    lines.append("\t{" + ", ".join(cell(v) for v in r) + "},\n")
lines.append("}\n")
print("".join(lines), end="")
