#!/usr/bin/env python3
"""Generate internal/initdb/pg_proc_initdb_overrides_generated.go (M0149-0001g
slice 16): the pg_proc columns that initdb's system_functions.sql changes after
bootstrap — CREATE OR REPLACE of built-ins that adds argument DEFAULTs and
names, rewrites SQL-language bodies into prosqlbody node trees (prosrc ''),
and adjusts cost/strictness/volatility/parallel — captured from a throwaway
PostgreSQL 18.3 initdb and emitted only where they differ from postgres.bki.

Usage: scripts/gen-pg-proc-initdb-overrides.py > internal/initdb/pg_proc_initdb_overrides_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
bki = os.path.join(root, "postgres", "src", "include", "catalog", "postgres.bki")
port = os.environ.get("GEN_PORT", "5547")


def fields(line):
    body = line[len("insert ( "):-len(" )")]
    out, cur, q, quoted = [], "", False, False
    for ch in body:
        if ch == "'":
            q, quoted = not q, True
            continue
        if ch == " " and not q:
            if cur or quoted:
                out.append(cur)
            cur, quoted = "", False
            continue
        cur += ch
    if cur or quoted:
        out.append(cur)
    return out


bkirows, inside = {}, False
with open(bki) as f:
    for line in f:
        line = line.rstrip("\n")
        if line.startswith("create pg_proc "):
            inside = True
        elif line == "close pg_proc":
            inside = False
        elif inside and line.startswith("insert ( "):
            r = fields(line)
            bkirows[int(r[0])] = r

tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    q = """select coalesce(json_agg(json_build_object(
          'oid', oid::int8, 'src', prosrc, 'body', prosqlbody::text, 'nargdef', pronargdefaults,
          'argdef', proargdefaults::text, 'argnames', array_to_json(proargnames),
          'cost', procost, 'rows', prorows, 'strict', proisstrict, 'vol', provolatile::text,
          'par', proparallel::text, 'lang', prolang::int8) order by oid), '[]')
        from pg_proc where oid < 16384"""
    out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki",
                          "-d", "postgres", "-At", "-c", q], env=env, check=True, capture_output=True, text=True).stdout
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)

rows = json.loads(out)
emit = []
for r in rows:
    b = bkirows.get(r["oid"])
    if b is None:
        continue  # created by initdb SQL (not a pg_proc.dat row) — out of scope here
    bargnames = None if b[22] == "_null_" else b[22].strip("{}").split(",")
    changed = (
        r["src"] != b[25] or r["body"] is not None or r["nargdef"] != int(b[17]) or r["argdef"] is not None
        or (r["argnames"] or None) != bargnames or int(r["cost"]) != int(b[5]) or int(r["rows"]) != int(b[6])
        or r["strict"] != (b[12] == "t") or r["vol"] != b[14] or r["par"] != b[15] or r["lang"] != int(b[4]))
    if changed:
        emit.append(r)


def gostr(s):
    return json.dumps(s, ensure_ascii=True)


lines = [
    "// Code generated by scripts/gen-pg-proc-initdb-overrides.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n",
    "package initdb\n\n",
    "// pgProcInitdbOverrides holds, for each built-in that initdb's\n",
    "// system_functions.sql re-creates, the pg_proc values it leaves (%d rows).\n" % len(emit),
    "var pgProcInitdbOverrides = map[uint32]pgProcInitdbOverride{\n",
]
for r in emit:
    names = "nil" if not r["argnames"] else "[]string{%s}" % ", ".join(gostr(n) for n in r["argnames"])
    lines.append("\t%d: {Src: %s, SqlBody: %s, NArgDefaults: %d, ArgDefaults: %s, ArgNames: %s, Cost: %d, Rows: %d, Strict: %s, Volatile: '%s', Parallel: '%s', Lang: %d},\n" % (
        r["oid"], gostr(r["src"]), gostr(r["body"] or ""), r["nargdef"], gostr(r["argdef"] or ""), names,
        int(r["cost"]), int(r["rows"]), "true" if r["strict"] else "false", r["vol"], r["par"], r["lang"]))
lines.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(lines), capture_output=True, text=True, check=True).stdout)
