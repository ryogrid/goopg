#!/usr/bin/env python3
"""Generate internal/initdb/pg_type_rowtypes_generated.go (M0149-0001g slice 18):
the pg_type rows a PostgreSQL 18.3 initdb holds for the composite rowtype of
every system relation (typrelid <> 0, OID < 16384) and for each rowtype's array
type, with the relation name each rowtype belongs to. Captured from a throwaway
initdb.

Usage: scripts/gen-pg-type-rowtypes.py > internal/initdb/pg_type_rowtypes_generated.go
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
bindir = os.path.join(root, "postgres", "local_install", "bin")
env = dict(os.environ, LD_LIBRARY_PATH=os.path.join(root, "postgres", "local_install", "lib"))
port = os.environ.get("GEN_PORT", "5547")
tmp = tempfile.mkdtemp()
data = os.path.join(tmp, "data")
try:
    subprocess.run([os.path.join(bindir, "initdb"), "-D", data, "-U", "genbki", "--no-sync", "-E", "UTF8", "--locale=C"],
                   env=env, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-l", os.path.join(tmp, "log"), "-w",
                    "-o", "-p %s -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s" % (port, tmp), "start"],
                   env=env, check=True, stdout=subprocess.DEVNULL)
    q = """with rt as (select t.oid from pg_type t where t.oid < 16384 and t.typrelid <> 0),
               sel as (select oid from rt union select a.oid from pg_type a join rt on a.typelem = rt.oid where a.oid < 16384)
        select coalesce(json_agg(json_build_object(
          'oid', t.oid::int8, 'name', t.typname::text, 'nsp', t.typnamespace::int8, 'len', t.typlen, 'byval', t.typbyval,
          'type', t.typtype::text, 'cat', t.typcategory::text, 'pref', t.typispreferred, 'def', t.typisdefined,
          'delim', t.typdelim::text, 'relid', t.typrelid::int8, 'relname', coalesce(c.relname::text, ''),
          'subscript', t.typsubscript::oid::int8, 'elem', t.typelem::int8, 'array', t.typarray::int8,
          'in', t.typinput::oid::int8, 'out', t.typoutput::oid::int8, 'recv', t.typreceive::oid::int8,
          'send', t.typsend::oid::int8, 'modin', t.typmodin::oid::int8, 'modout', t.typmodout::oid::int8,
          'analyze', t.typanalyze::oid::int8, 'align', t.typalign::text, 'storage', t.typstorage::text,
          'notnull', t.typnotnull, 'base', t.typbasetype::int8, 'typmod', t.typtypmod, 'ndims', t.typndims,
          'coll', t.typcollation::int8, 'extra', (t.typdefaultbin is not null or t.typdefault is not null or t.typacl is not null))
          order by t.oid), '[]')
        from pg_type t join sel on sel.oid = t.oid left join pg_class c on c.oid = t.typrelid"""
    out = subprocess.run([os.path.join(bindir, "psql"), "-X", "-h", "127.0.0.1", "-p", port, "-U", "genbki",
                          "-d", "postgres", "-At", "-c", q], env=env, check=True, capture_output=True, text=True).stdout
finally:
    subprocess.run([os.path.join(bindir, "pg_ctl"), "-D", data, "-m", "immediate", "stop"], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    shutil.rmtree(tmp, ignore_errors=True)
rows = json.loads(out)
if any(r["extra"] for r in rows):
    sys.exit("a rowtype carries typdefault/typdefaultbin/typacl; the generator does not model them")
B = lambda v: "true" if v else "false"
lines = [
    "// Code generated by scripts/gen-pg-type-rowtypes.py from a PostgreSQL 18.3 initdb; DO NOT EDIT.\n\n",
    "package initdb\n\n",
    "// pgTypeInitdbRowtypes are the pg_type rows a PG 18.3 initdb holds for system\n",
    "// relations' composite rowtypes and their array types (%d rows).\n" % len(rows),
    "var pgTypeInitdbRowtypes = []pgTypeFullRow{\n",
]
for r in rows:
    lines.append("\t{%d, %s, %d, %d, %s, '%s', '%s', %s, %s, '%s', %d, %s, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, '%s', '%s', %s, %d, %d, %d, %d},\n" % (
        r["oid"], json.dumps(r["name"]), r["nsp"], r["len"], B(r["byval"]), r["type"], r["cat"], B(r["pref"]), B(r["def"]),
        r["delim"], r["relid"], json.dumps(r["relname"]), r["subscript"], r["elem"], r["array"], r["in"], r["out"], r["recv"],
        r["send"], r["modin"], r["modout"], r["analyze"], r["align"], r["storage"], B(r["notnull"]), r["base"], r["typmod"],
        r["ndims"], r["coll"]))
lines.append("}\n")
sys.stdout.write(subprocess.run(["gofmt"], input="".join(lines), capture_output=True, text=True, check=True).stdout)
